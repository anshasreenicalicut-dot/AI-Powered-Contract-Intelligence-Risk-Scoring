import argparse
import json
from pathlib import Path

import spacy


TARGET_LABELS = {"ORG", "DATE", "MONEY"}


def load_jsonl_records(path):
    with path.open("r", encoding="utf-8") as file:
        for line_number, line in enumerate(file, start=1):
            if not line.strip():
                continue

            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                print(f"[WARNING] Invalid JSON on line {line_number}")
                continue

            text = (
                record.get("text")
                or record.get("context")
                or record.get("contract_text")
                or ""
            )

            if text.strip():
                yield {
                    "id": record.get(
                        "contract_id",
                        record.get("id", f"record_{line_number}")
                    ),
                    "source": str(path),
                    "text": text
                }


def load_text_files(folder):
    folder = Path(folder)

    for path in sorted(folder.rglob("*.txt")):
        try:
            text = path.read_text(
                encoding="utf-8",
                errors="replace"
            )

            if text.strip():
                yield {
                    "id": path.stem,
                    "source": str(path),
                    "text": text
                }

        except OSError as error:
            print(f"[WARNING] Cannot read {path}: {error}")


def main():
    parser = argparse.ArgumentParser(
        description="Extract named entities from contract text."
    )

    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument(
        "--input-dir",
        help="Folder containing extracted TXT files"
    )
    group.add_argument(
        "--input-jsonl",
        help="JSONL file generated by prepare_data.py"
    )

    parser.add_argument(
        "--output-dir",
        default="outputs/ner_results"
    )
    parser.add_argument(
        "--model",
        default="en_core_web_sm"
    )

    args = parser.parse_args()

    try:
        nlp = spacy.load(args.model)
    except OSError:
        raise SystemExit(
            f"Model {args.model} is not installed. Run:\n"
            f"python -m spacy download {args.model}"
        )

    if args.input_dir:
        records = load_text_files(args.input_dir)
    else:
        records = load_jsonl_records(Path(args.input_jsonl))

    output_dir = Path(args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    output_file = output_dir / "ner_results.jsonl"
    counts = {label: 0 for label in sorted(TARGET_LABELS)}
    document_count = 0
    entity_count = 0

    with output_file.open("w", encoding="utf-8") as file:
        for record in records:
            # Limit exceptionally large input documents for this baseline.
            doc = nlp(record["text"][:1_000_000])
            entities = []

            for entity in doc.ents:
                if entity.label_ not in TARGET_LABELS:
                    continue

                entities.append({
                    "text": entity.text,
                    "label": entity.label_,
                    "start_char": entity.start_char,
                    "end_char": entity.end_char
                })

                counts[entity.label_] += 1

            result = {
                "document_id": record["id"],
                "source": record["source"],
                "entities": entities
            }

            file.write(
                json.dumps(result, ensure_ascii=False) + "\n"
            )

            document_count += 1
            entity_count += len(entities)

            print(
                f"[OK] {record['id']}: "
                f"{len(entities)} entities found"
            )

    summary = {
        "model": args.model,
        "documents_processed": document_count,
        "entities_extracted": entity_count,
        "counts_by_label": counts,
        "entity_types": sorted(TARGET_LABELS),
        "note": "Pretrained baseline; validate entity predictions."
    }

    summary_file = output_dir / "ner_summary.json"
    summary_file.write_text(
        json.dumps(summary, indent=2, ensure_ascii=False),
        encoding="utf-8"
    )

    print("\nNER processing completed.")
    print(f"Results: {output_file}")
    print(f"Summary: {summary_file}")
    print(f"Documents processed: {document_count}")
    print(f"Entities extracted: {entity_count}")


if __name__ == "__main__":
    main()